"""The OAuth seam: authorize, exchange, refresh, revoke — with a fake, and no real client.

Every platform in ``docs/CHANNELS.md`` §2 that we could publish to uses the same four
operations, in the same order, with the same failure modes. So this is one port with one
fake behind it, and a real adapter per platform is added the day that platform's App
Review is actually approved.

**One real adapter now exists — :mod:`platform_oauth_meta`, for ``facebook`` and
``instagram`` — and it changes nothing about what may be PUBLISHED.** ``docs/CHANNELS.md``
§2-3 is unchanged and still explicit: Facebook Page and Instagram publishing need Meta App
Review (screencast, privacy policy, business verification, two to six weeks, refusable by
form letter); LinkedIn company-page posting needs Marketing Developer Platform approval;
TikTok's unaudited apps are confined to private/self-only visibility. So what the Meta
adapter buys is precisely the CONNECTION lifecycle against the live platform — a real
consent dialog, a real long-lived credential, a real renewal, a real de-authorisation —
and :func:`oauth_status` says both halves out loud, because a screen that reports "real
provider" without reporting "publishing is still in somebody else's queue" is a support
ticket.

**No LinkedIn or TikTok client is written here, and that is still a decision rather than a
gap.** A client written against those APIs today could not be exercised end to end — not
by a test (this suite makes no network calls, ever) and not by hand (there is no approved
app to authenticate against). It would be untested code shaped like a feature, which is
worse than an honest absence, because the absence is visible and the untested code is not.
The Meta adapter is subject to the same limit and does not pretend otherwise: every path
in it is proven against an injected ``httpx.MockTransport``, and the first real
round-trip happens the day somebody sets ``META_APP_ID`` and ``META_APP_SECRET``.

What IS buildable now, and what the rest of the system is waiting on, is this shape:

* an authorization URL a human can be sent to,
* a code-for-token exchange that yields a credential with an expiry and a scope list,
* a refresh, because every one of these tokens expires and an integration that cannot
  renew is an integration that breaks quietly a month after it is set up,
* a revoke, so disconnecting means something on the platform's side and not just in our
  database.

:class:`FakeOAuthProvider` implements all four with no I/O, which is what makes the whole
connect → expire → refresh → revoke lifecycle testable today. It follows the same rule
the model router follows and ``CLAUDE.md`` states: a missing credential means the fake,
plus a status that says so — never a silent no-op and never a claim that something
happened outside this process.

The one piece a fake provider cannot fake by itself is the CONSENT SCREEN, and without it
the lifecycle above was reachable only from a test. The authorization URL used to point at
``fake-oauth.invalid`` — RFC 2606 reserved, so it can never resolve — which meant a human
could start a connect and never finish one: the browser had nowhere to go, so the callback
was never called, so no connection could be created from the UI at all. That is what
:func:`fake_consent_path` fixes. A fake provider's authorization URL now points at a
stand-in consent screen served by ``api/connections.py`` **on our own origin**, carrying
the same ``redirect_uri`` and ``state`` a platform would have been handed, and that screen
sends the browser back to ``redirect_uri`` with a code and the state it was given.

**This is a stand-in, not a bypass, and the distinction is mechanical rather than a
promise.** The ``state`` cookie is written by ``POST /connect`` on our origin, the browser
holds it, and the callback is on that same origin — so the cookie is presented by the
browser in the ordinary way and ``api/oauth_state.verify_state`` plus
``nonce_matches`` run exactly as designed, against a nonce that travelled through the URL
and not through the cookie. Nothing is forged, nothing is skipped, and a callback whose
``state`` does not match is refused after this change exactly as it was before it. A fake
provider standing in for a third party is what a fake provider IS; the unreachable
``.invalid`` URL was standing in for a consent screen that does not exist, and this
replaces it with one that does.

The state parameter is generated by the caller (``connection_service.begin_connect``) and
is NOT stored here. This module holds no session and no database; a provider that
remembered state would be a provider with a side effect, and there would then be two
places that decide whether a callback is genuine.
"""

